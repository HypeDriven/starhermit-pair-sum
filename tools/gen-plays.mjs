// Writes the generated native play scripts in tests/native/ from the rules:
// the board is played in node with the shipped rules and content (the
// lesson's required pair first, else the first legal pair, Add rows when
// nothing connects), and each pair becomes two presses on the tokens' named
// targets ("Row r, column c, digit v", the old DOM mirror's cell labels).
//   journey-1.play   Journey page 1 on a desktop, clicked with the mouse, to its results
//   learn-phone.play lessons 1 to 6 on a phone (DPR 3), touched, each to its results
//   node tools/gen-plays.mjs
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createGame, applyCommand, listLegalPairs } from '../js/rules.js';
import { JOURNEY, LESSONS } from '../js/content.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const name = (s, i) => `Row ${Math.floor(i / s.cols) + 1}, column ${(i % s.cols) + 1}, digit ${s.cells[i]}`;

/** The steps that clear `def`: { pair: [a, b] names } or { addRows }. */
export function solve(def) {
  let s = createGame(def);
  const steps = [];
  let lesson = 0;
  const lessonSteps = def.tutorial?.steps ?? [];
  for (let k = 0; k < 400 && s.status === 'active'; k++) {
    const req = lessonSteps[lesson]?.require;
    const legal = listLegalPairs(s);
    let pick = legal[0];
    if (req?.type === 'pair') {
      const want = req.values.slice().sort().join(',');
      pick = legal.find((p) => [s.cells[p.a], s.cells[p.b]].sort().join(',') === want);
    }
    if (!pick || req?.type === 'any-addrows') {
      const r = applyCommand(s, { id: s.nextCmdId, at: 0, type: 'addRows' });
      if (r.error) throw new Error(`${def.id}: stuck (${r.error})`);
      steps.push({ addRows: true });
      s = r.state;
      lesson++;
      continue;
    }
    steps.push({ pair: [name(s, pick.a), name(s, pick.b)] });
    s = applyCommand(s, { id: s.nextCmdId, at: 0, type: 'pair', a: pick.a, b: pick.b }).state;
    lesson++;
  }
  if (s.status !== 'won') throw new Error(`${def.id}: ended ${s.status}`);
  return steps;
}

function lines(steps, press) {
  const out = [];
  for (const st of steps) {
    if (st.addRows) { out.push(`${press} =Add rows`, 'frames 40'); continue; }
    out.push(`${press} =${st.pair[0]}`, 'frames 8', `${press} =${st.pair[1]}`, 'frames 40');
  }
  return out;
}

const journey = [
  '# Generated by tools/gen-plays.mjs: Journey page 1 on a desktop (1280 x 800), from the title through the',
  '# modes and the stage grid, every pair clicked on the tokens\' named targets, to the results and the',
  '# next page\'s countdown.',
  '# viewport 1280x800@1',
  'until 600 Daily challenge',
  'frames 10',
  'click =Play',
  'until 120 Choose a mode',
  'frames 10',
  'click =Journey',
  'until 120 Forty pages across five notebooks',
  'frames 10',
  'save journey',
  'click =1. First Lines',
  'until 120 Equal numbers and small sums.',
  'frames 10',
  'click =Start',
  'until 300 digits left',
  'frames 170',
  'save journey-board',
  ...lines(solve(JOURNEY[0]), 'click'),
  'until 300 Page cleared!',
  'frames 30',
  'save journey-results',
  'expect Total',
  'click =Next page',
  'until 300 2. Tens',
  'frames 30',
];
writeFileSync(join(root, 'tests/native/journey-1.play'), journey.join('\n') + '\n');

const learn = [
  '# Generated by tools/gen-plays.mjs: the six lessons on a phone (390 x 844, DPR 3), each move touched on',
  '# the tokens\' named targets (lesson 6 adds rows from the tray), each lesson to its results and the next.',
  '# viewport 390x844@3',
  'until 600 Daily challenge',
  'frames 10',
  'touch =Play',
  'until 120 Choose a mode',
  'frames 10',
  'touch =Learn',
  'until 120 Pick a lesson',
  'frames 10',
  'save learn-list',
  'touch =1. Equal neighbours',
];
LESSONS.forEach((l, i) => {
  learn.push('until 300 digits left', 'frames 40');
  if (i === 0 || i === 5) learn.push(`save lesson-${i + 1}`);
  learn.push(...lines(solve(l), 'touch'));
  learn.push('until 300 Page cleared!', 'frames 20');
  if (i === 0) learn.push('save lesson-1-results');
  if (i < LESSONS.length - 1) learn.push('touch =Next lesson');
});
learn.push('touch =Next lesson', 'until 300 Daily challenge');
writeFileSync(join(root, 'tests/native/learn-phone.play'), learn.join('\n') + '\n');
console.log('wrote tests/native/journey-1.play, tests/native/learn-phone.play');
